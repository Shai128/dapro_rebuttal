"""Load source-model predictions on arbitrary calibration or test setups."""

from __future__ import annotations

import torch

from src.predictive_bounds.experiments.cross_setup.utils import (
    setup_source_model_evaluation_data,
)
from src.predictive_bounds.utils.utils import setup_experiment_data


def load_prediction_pool(
        *,
        model_dataset_name: str,
        evaluation_dataset_name: str,
        model_dataset_setup: str,
        evaluation_dataset_setup: str,
        device: str | torch.device,
        taus_range: torch.Tensor,
        m_upper_bound: float,
):
    """Return all calibration/test rows from one evaluation setup.

    If the model and evaluation setup coincide, the ordinary prediction cache
    is used.  Otherwise the existing cross-setup inference cache applies the
    source model to the evaluation trajectories.  No conversations are
    regenerated by this helper.
    """
    if (
        model_dataset_name == evaluation_dataset_name
        and model_dataset_setup == evaluation_dataset_setup
    ):
        return setup_experiment_data(
            1,
            True,
            device,
            evaluation_dataset_name,
            evaluation_dataset_setup,
            taus_range,
            m_upper_bound,
        )
    return setup_source_model_evaluation_data(
        cal_size=1,
        is_real=True,
        device=device,
        model_dataset_name=model_dataset_name,
        evaluation_dataset_name=evaluation_dataset_name,
        model_dataset_setup=model_dataset_setup,
        evaluation_dataset_setup=evaluation_dataset_setup,
        taus_range=taus_range,
        m_upper_bound=m_upper_bound,
    )


def select_shift_indices(
        population_size: int,
        requested_size: int,
        seed: int,
) -> torch.Tensor:
    if requested_size < 0:
        raise ValueError("requested_size cannot be negative.")
    size = population_size if requested_size == 0 else requested_size
    if size > population_size:
        raise ValueError(
            f"Requested {size} rows from a population of {population_size}."
        )
    generator = torch.Generator(device="cpu").manual_seed(int(seed))
    return torch.randperm(population_size, generator=generator)[:size]
