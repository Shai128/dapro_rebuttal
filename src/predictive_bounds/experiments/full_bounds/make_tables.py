"""Write one copy-paste-ready LaTeX file with every comparison table."""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from src.predictive_bounds.experiments.full_bounds.config import (
    METHOD_ORDER,
    TARGET_MODELS,
    select_configs,
)
from src.predictive_bounds.experiments.full_bounds.summarize import (
    DEFAULT_OUTPUT_DIR,
    ROOT,
    load_comparison_data,
)


METRICS = (
    ("mean_weight", r"Mean $1/\pi$"),
    ("mean_a_weight", r"Mean $A/\pi$"),
    ("coverage_variance_pp2", r"Cov. var. (pp$^2$)"),
    ("coverage_pct", r"Coverage (\%)"),
    ("coverage_diff_pct", r"$|$Cov.-target$|$ (pp)"),
    ("budget_used_per_sample", r"Budget/sample"),
    ("size", r"Mean bound"),
    ("infinite_bound_rate_pct", r"UPB=201 (\%)"),
)


def _escape_latex(value: str) -> str:
    replacements = {
        "&": r"\&",
        "%": r"\%",
        "_": r"\_",
        "#": r"\#",
    }
    return "".join(replacements.get(character, character) for character in value)


def _format_mean_std(mean: float, std: float, *, variance=False) -> str:
    if not np.isfinite(mean):
        return "--"
    if variance:
        return f"{mean:.3f}"
    if not np.isfinite(std):
        return f"{mean:.3f}"
    return rf"{mean:.3f} $\pm$ {std:.3f}"


def _best_method(
        summary: pd.DataFrame,
        metric: str,
        target_coverage: float,
        target_budget: float,
) -> str | None:
    candidates = summary[np.isfinite(summary[metric])].copy()
    candidates = candidates[
        ~candidates["method"].isin(
            [
                "Raw",
                "Oracle",
                "Uncalibrated",
                "Infinite-Budget Oracle",
                "DAPRO Oracle (split)",
                "DAPRO Oracle + CRC",
                "DAPRO Oracle (global)",
            ]
        )
    ]
    if candidates.empty:
        return None
    if metric == "coverage_pct":
        score = (candidates[metric] - target_coverage).abs()
        return str(candidates.loc[score.idxmin(), "method"])
    if metric == "budget_used_per_sample":
        feasible = candidates[
            candidates[metric] <= target_budget + 1e-9
        ]
        if not feasible.empty:
            return str(feasible.loc[feasible[metric].idxmax(), "method"])
        return str(candidates.loc[
            (candidates[metric] - target_budget).abs().idxmin(), "method"
        ])
    return str(candidates.loc[candidates[metric].idxmin(), "method"])


def _configuration_summary(frame: pd.DataFrame) -> pd.DataFrame:
    ordinary = (
        frame.groupby("method", observed=True)[[
            "mean_weight",
            "mean_a_weight",
            "coverage_pct",
            "coverage_diff_pct",
            "budget_used_per_sample",
            "size",
            "infinite_bound_rate_pct",
        ]]
        .agg(["mean", "std"])
    )
    rows = []
    ordered_methods = list(METHOD_ORDER)
    ordered_methods.extend(
        method for method in ordinary.index if method not in ordered_methods
    )
    for method in ordered_methods:
        if method not in ordinary.index:
            continue
        row = {"method": method}
        for metric in [
            "mean_weight",
            "mean_a_weight",
            "coverage_pct",
            "coverage_diff_pct",
            "budget_used_per_sample",
            "size",
            "infinite_bound_rate_pct",
        ]:
            row[metric] = ordinary.loc[method, (metric, "mean")]
            row[f"{metric}_std"] = ordinary.loc[method, (metric, "std")]
        values = frame.loc[frame["method"] == method, "coverage_pct"]
        row["coverage_variance_pp2"] = values.var(ddof=1)
        row["coverage_variance_pp2_std"] = np.nan
        rows.append(row)
    return pd.DataFrame(rows)


def render_latex_tables(frame: pd.DataFrame) -> str:
    blocks = [
        "% Generated by src.predictive_bounds.experiments.full_bounds.make_tables",
        "% Requires \\usepackage{booktabs,graphicx}. Bold entries are the best",
        "% among feasible calibrated allocation methods. The infinite-budget",
        "% oracle is shown as a benchmark and is never eligible for boldface.",
        "% Budget is the greatest mean",
        "% utilization at or below the target (or the closest if none is below).",
        "",
    ]
    grouped = frame.groupby(
        ["configuration", "dataset_display", "bound_type", "target_model"],
        sort=False,
        observed=True,
    )
    for (
            configuration,
            dataset_display,
            bound_type,
            target_model,
    ), group in grouped:
        summary = _configuration_summary(group)
        target_coverage = float(group["target_coverage_pct"].iloc[0])
        target_budget = float(group["target_budget"].iloc[0])
        best = {
            metric: _best_method(
                summary,
                metric,
                target_coverage,
                target_budget,
            )
            for metric, _ in METRICS
        }
        caption = (
            f"{dataset_display}, {target_model}, {bound_type}: "
            f"target coverage {target_coverage:.0f}% and budget "
            f"{target_budget:g} per sample. Values are mean $\\pm$ standard "
            "deviation across splits; coverage variance is across-split "
            "sample variance."
        )
        label = "tab:full_bounds_" + configuration.replace("__", "_")
        blocks.extend([
            r"\begin{table*}[t]",
            r"\centering",
            r"\small",
            rf"\caption{{{_escape_latex(caption)}}}",
            rf"\label{{{label}}}",
            r"\resizebox{\textwidth}{!}{%",
            rf"\begin{{tabular}}{{l{'r' * len(METRICS)}}}",
            r"\toprule",
            "Method & " + " & ".join(header for _, header in METRICS) + r" \\",
            r"\midrule",
        ])
        for _, row in summary.iterrows():
            cells = []
            for metric, _ in METRICS:
                cell = _format_mean_std(
                    float(row[metric]),
                    float(row[f"{metric}_std"]),
                    variance=(metric == "coverage_variance_pp2"),
                )
                if best[metric] == row["method"] and cell != "--":
                    cell = rf"\textbf{{{cell}}}"
                cells.append(cell)
            blocks.append(
                _escape_latex(str(row["method"]))
                + " & " + " & ".join(cells) + r" \\"
            )
        blocks.extend([
            r"\bottomrule",
            r"\end{tabular}",
            r"}%",
            r"\end{table*}",
            "",
        ])
    return "\n".join(blocks)


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--suffix", default="full_bounds_v4_soft_upb")
    parser.add_argument(
        "--output", type=Path,
        default=DEFAULT_OUTPUT_DIR / "full_bounds_tables.tex",
    )
    parser.add_argument("--config", action="append", dest="configs")
    parser.add_argument(
        "--target-model",
        action="append",
        choices=[model.key for model in TARGET_MODELS],
    )
    parser.add_argument(
        "--bound-type", action="append", choices=["lpb", "upb"]
    )
    parser.add_argument("--available-only", action="store_true")
    parser.add_argument("--allow-missing", action="store_true")
    return parser.parse_args()


def main() -> None:
    args = _parse_args()
    configs = select_configs(
        ROOT,
        keys=set(args.configs or []),
        target_models=set(args.target_model or []),
        bound_types=set(args.bound_type or []),
        available_only=args.available_only,
    )
    if not configs:
        raise SystemExit("No configurations matched the requested filters.")
    frame = load_comparison_data(
        configs,
        args.suffix,
        allow_missing=args.allow_missing,
    )
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_latex_tables(frame), encoding="utf-8")
    print(args.output.resolve())


if __name__ == "__main__":
    main()
